#!/usr/bin/env Rscript
suppressPackageStartupMessages({library(phyloseq); library(readr); library(vegan)})
root <- normalizePath(getwd())
out <- file.path(root, "results", "primary")
dir.create(out, recursive=TRUE, showWarnings=FALSE)
ps <- readRDS(file.path(root,"data/references/sinusitis_microbiome/AnalysisPhyloseq.rds"))
counts <- as(otu_table(ps), "matrix")
if (taxa_are_rows(ps)) counts <- t(counts)
stopifnot(!anyDuplicated(rownames(counts)), all(rowSums(counts)>0))
meta <- data.frame(sample_data(ps), check.names=FALSE)
meta$phyloseq_sample_id <- rownames(meta)
meta$sample_id <- as.character(meta$X.SampleID)
meta$matrix_sample_id <- ifelse(meta$sample_id %in% rownames(counts),meta$sample_id,meta$phyloseq_sample_id)
meta$child_id <- as.character(meta$PatID)
meta$outcome_group <- as.character(meta$sinusitis_vs_uri)
meta$sinusitis_binary <- ifelse(meta$outcome_group=="Sinusitis",1L,ifelse(meta$outcome_group=="URI",0L,NA))
meta$ecological_cluster <- as.character(meta$CanberraClusters)
meta$cluster_i <- as.integer(meta$ecological_cluster=="I")
clean <- function(x) {x<-sub("^.*g__","",as.character(x));x[is.na(x)|x==""]<-"Unclassified";x}
meta$dominant_genus <- clean(meta$dom_gen)
meta$dominant_genus_fraction <- as.numeric(meta$domgen_pct)
meta$daycare <- as.character(meta$Daycare_Initial)
meta$tobacco_exposure <- as.character(meta$Tobacco.Exposure_Initial)
meta$virus_count <- suppressWarnings(as.numeric(meta$tot.virus.in.samp))
meta$shannon <- diversity(counts[meta$matrix_sample_id,,drop=FALSE],index="shannon")
quoted_write <- function(df,path) write_delim(df,path,delim="\t",quote="needed",escape="double",na="NA")
target <- file.path(root,"data/processed/prjeb35160_sample_metadata.tsv")
quoted_write(meta,target)
back <- read_tsv(target,col_types=cols(.default=col_character()),trim_ws=FALSE,show_col_types=FALSE)
stopifnot(nrow(back)==nrow(meta),identical(back$sample_id,meta$sample_id),!anyDuplicated(back$sample_id))
for (name in names(meta)) {
  original <- as.character(meta[[name]])
  if (is.numeric(meta[[name]])) {
    stopifnot(isTRUE(all.equal(suppressWarnings(as.numeric(back[[name]])),meta[[name]],check.attributes=FALSE,tolerance=1e-12)))
  } else if (!identical(back[[name]],original)) stop(paste("Round-trip mismatch in",name))
}
tax <- data.frame(tax_table(ps),check.names=FALSE)
tax$genus_label <- clean(tax$genus)
tax$taxon_id <- rownames(tax)
rel <- counts/rowSums(counts)
genus <- t(rowsum(t(rel),group=tax$genus_label,reorder=FALSE))
genus_df <- data.frame(matrix_sample_id=rownames(genus),genus,check.names=FALSE)
quoted_write(genus_df,file.path(out,"genus_relative_abundance.tsv"))
quoted_write(data.frame(matrix_sample_id=rownames(rel),rel,check.names=FALSE),file.path(out,"otu_relative_abundance.tsv"))
quoted_write(tax,file.path(out,"taxonomy.tsv"))
quoted_write(data.frame(check=c("metadata_roundtrip_all_fields","source_profiles","source_children","duplicate_ids","total_abundance"),value=c("PASS",nrow(meta),length(unique(meta$child_id)),0,max(abs(rowSums(genus)-1)))),file.path(out,"input_integrity.tsv"))
capture.output(sessionInfo(),file=file.path(out,"R_sessionInfo.txt"))
cat("Exported and verified",nrow(meta),"profiles from",length(unique(meta$child_id)),"children\n")
